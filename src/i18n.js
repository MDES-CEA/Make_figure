/**
 * Traduit un message de statut. Les motifs sont essayés dans l'ordre ; à
 * défaut, la traduction exacte du dictionnaire puis le texte source.
 */
export function translateMessage(text, language) {
  if (!language || language === "fr" || typeof text !== "string" || !text) return text;
  for (const [pattern, replacement] of EN_MESSAGES) {
    if (pattern.test(text)) return text.replace(pattern, replacement);
  }
  return translate(text, language);
}
