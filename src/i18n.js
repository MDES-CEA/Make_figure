const DICTIONARIES = { en: EN };

/** Traduit une chaîne source française vers la langue demandée. */
export function translate(text, language) {
  if (!language || language === "fr") return text;
  if (typeof text !== "string") return text;
  const dictionary = DICTIONARIES[language];
  if (!dictionary) return text;
  return dictionary[text] ?? text;
}

export const SUPPORTED_LANGUAGES = [["fr", "Français"], ["en", "English"]];

/** Libellés d'axes par défaut, par espace et par langue. */
export function defaultAxisLabels(mode, language, irQuantity = "absorbance") {
  const english = language === "en";
  if (mode === "drx") {
    return {
      xlabel: "2θ (°, Cu Kα, λ = 1.5406 Å)",
      ylabel: english ? "Intensity (a.u.)" : "Intensité (u. a.)",
    };
  }
  if (mode === "ir") {
    return {
      xlabel: english ? "Wavenumber (cm⁻¹)" : "Nombre d’onde (cm⁻¹)",
      ylabel: irQuantity === "transmittance"
        ? (english ? "Transmittance (%)" : "Transmittance (%)")
        : (english ? "Absorbance (a.u.)" : "Absorbance (u. a.)"),
    };
  }
  return {
    xlabel: english ? "Raman shift (cm⁻¹)" : "Décalage Raman (cm⁻¹)",
    ylabel: english ? "Intensity (a.u.)" : "Intensité (u. a.)",
  };
}
